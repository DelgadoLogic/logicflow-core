        #region Vector 3: IFEO, AppInit & Winlogon

        private List<PersistenceThreatItem> AuditIfeoAppInitAndWinlogon(ref int itemsScanned, PersistenceScanReport report)
        {
            var threats = new List<PersistenceThreatItem>();
            string ifeoPath = @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options";

            // Inspect IFEO across both 64-bit and 32-bit registry views
            var views = new[] { RegistryView.Registry64, RegistryView.Registry32 };
            foreach (var view in views)
            {
                string viewLabel = view == RegistryView.Registry64 ? "64-bit" : "32-bit WOW64";
                string[] subKeyNames;
                try
                {
                    subKeyNames = _registry.GetSubKeyNames(RegistryHive.LocalMachine, view, ifeoPath);
                }
                catch (UnauthorizedAccessException)
                {
                    report.RequiresElevation = true;
                    continue;
                }
                catch
                {
                    continue;
                }

                foreach (var subName in subKeyNames)
                {
                    itemsScanned++;
                    string subPath = $@"{ifeoPath}\{subName}";
                    var debugger = _registry.GetString(RegistryHive.LocalMachine, view, subPath, "Debugger");

                    if (!string.IsNullOrWhiteSpace(debugger))
                    {
                        bool isAccessibility = AccessibilityBinaryCatalog.Contains(subName);
                        bool isDevDebugger = debugger.Contains("vsjitdebugger.exe", StringComparison.OrdinalIgnoreCase) ||
                                             debugger.Contains("windbg.exe", StringComparison.OrdinalIgnoreCase);

                        ThreatSeverity severity = isAccessibility
                            ? ThreatSeverity.Critical
                            : (isDevDebugger ? ThreatSeverity.Low : ThreatSeverity.High);

                        threats.Add(new PersistenceThreatItem
                        {
                            Id = $"ifeo_{subName}_{viewLabel}",
                            Category = "IFEO Hijack",
                            Name = $"Debugger Hook on {subName} ({viewLabel})",
                            Location = $@"HKLM\{subPath}\Debugger",
                            CommandOrValue = debugger,
                            Severity = severity,
                            Description = isAccessibility
                                ? "Critical accessibility binary intercepted by custom debugger (Sticky Keys lockscreen backdoor pattern)."
                                : $"Executable intercepted by debugger redirection: {debugger}",
                            TargetType = "IFEO",
                            AdditionalData = $"{subName}|{view}"
                        });
                    }

                    // Check for SilentProcessExit FLG_MONITOR_SILENT_PROCESS_EXIT (0x200)
                    var globalFlag = _registry.GetDword(RegistryHive.LocalMachine, view, subPath, "GlobalFlag");
                    if (globalFlag.HasValue && (globalFlag.Value & 0x200) != 0)
                    {
                        string silentKey = $@"SOFTWARE\Microsoft\Windows NT\CurrentVersion\SilentProcessExit\{subName}";
                        var monitorProcess = _registry.GetString(RegistryHive.LocalMachine, view, silentKey, "MonitorProcess");

                        if (!string.IsNullOrWhiteSpace(monitorProcess))
                        {
                            threats.Add(new PersistenceThreatItem
                            {
                                Id = $"silent_exit_{subName}_{viewLabel}",
                                Category = "SilentProcessExit Hijack",
                                Name = $"SilentProcessExit on {subName} ({viewLabel})",
                                Location = $@"HKLM\{silentKey}\MonitorProcess",
                                CommandOrValue = monitorProcess,
                                Severity = ThreatSeverity.Critical,
                                Description = $"SilentProcessExit persistence monitors termination of {subName} to execute: {monitorProcess}",
                                TargetType = "IFEO",
                                AdditionalData = $"{subName}|{view}"
                            });
                        }
                    }
                }

                // Inspect AppInit_DLLs
                string winPath = @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Windows";
                itemsScanned++;
                var appInit = _registry.GetString(RegistryHive.LocalMachine, view, winPath, "AppInit_DLLs");
                var loadAppInit = _registry.GetDword(RegistryHive.LocalMachine, view, winPath, "LoadAppInit_DLLs");

                if (!string.IsNullOrWhiteSpace(appInit))
                {
                    bool isActive = loadAppInit == 1 || loadAppInit == null;
                    threats.Add(new PersistenceThreatItem
                    {
                        Id = $"appinit_{viewLabel}",
                        Category = "DLL Injection",
                        Name = $"AppInit_DLLs {(isActive ? "Active" : "Dormant")} ({viewLabel})",
                        Location = $@"HKLM\{winPath}\AppInit_DLLs",
                        CommandOrValue = appInit,
                        Severity = isActive ? ThreatSeverity.Critical : ThreatSeverity.Medium,
                        Description = isActive
                            ? "AppInit_DLLs is active and forces custom DLL injection into all loaded user GUI processes."
                            : "AppInit_DLLs is configured but LoadAppInit_DLLs is disabled (0).",
                        TargetType = "AppInit",
                        AdditionalData = view.ToString()
                    });
                }
            }

            // Inspect Winlogon Overrides
            string winlogonPath = @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon";
            itemsScanned += 2;
            var shell = _registry.GetString(RegistryHive.LocalMachine, RegistryView.Registry64, winlogonPath, "Shell") ?? "explorer.exe";
            var userinit = _registry.GetString(RegistryHive.LocalMachine, RegistryView.Registry64, winlogonPath, "Userinit") ?? "";

            if (!shell.Trim().Equals("explorer.exe", StringComparison.OrdinalIgnoreCase))
            {
                threats.Add(new PersistenceThreatItem
                {
                    Id = "winlogon_shell",
                    Category = "Winlogon Hijack",
                    Name = "Non-standard Winlogon Shell",
                    Location = $@"HKLM\{winlogonPath}\Shell",
                    CommandOrValue = shell,
                    Severity = ThreatSeverity.Critical,
                    Description = $"Winlogon Shell has been overridden from default 'explorer.exe' to: '{shell}'",
                    TargetType = "Winlogon"
                });
            }

            string cleanUserinit = userinit.Trim().TrimEnd(',').ToLowerInvariant();
            bool isStandardUserinit = cleanUserinit == @"c:\windows\system32\userinit.exe" ||
                                      cleanUserinit == "userinit.exe" ||
                                      cleanUserinit == @"%systemroot%\system32\userinit.exe";

            if (!string.IsNullOrWhiteSpace(userinit) && !isStandardUserinit)
            {
                threats.Add(new PersistenceThreatItem
                {
                    Id = "winlogon_userinit",
                    Category = "Winlogon Hijack",
                    Name = "Compromised Userinit Path",
                    Location = $@"HKLM\{winlogonPath}\Userinit",
                    CommandOrValue = userinit,
                    Severity = ThreatSeverity.Critical,
                    Description = $"Winlogon Userinit has been modified to non-standard executable: '{userinit}'",
                    TargetType = "Winlogon"
                });
            }

            return threats;
        }

        #endregion

        #region Vector 4: Temp, AppData, ProgramData Unsigned Binaries & Running Processes

        private List<PersistenceThreatItem> AuditStagedAndRunningBinaries(ref int itemsScanned)
        {
            var threats = new List<PersistenceThreatItem>();
            var inspectedPaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            var stagingDirectories = new List<string>();

            // Collect staging paths
            try
            {
                string temp = Path.GetTempPath();
                if (!string.IsNullOrEmpty(temp) && _fileSystem.DirectoryExists(temp)) stagingDirectories.Add(temp);

                string appData = Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData);
                if (!string.IsNullOrEmpty(appData) && _fileSystem.DirectoryExists(appData)) stagingDirectories.Add(appData);

                string localAppData = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
                if (!string.IsNullOrEmpty(localAppData) && _fileSystem.DirectoryExists(localAppData)) stagingDirectories.Add(localAppData);

                string programData = Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData);
                if (!string.IsNullOrEmpty(programData) && _fileSystem.DirectoryExists(programData)) stagingDirectories.Add(programData);

                string winTemp = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Windows), "Temp");
                if (_fileSystem.DirectoryExists(winTemp)) stagingDirectories.Add(winTemp);
            }
            catch { }

            // 1. Audit active running processes from staging/user directories
            var running = _processProvider.GetRunningProcesses();
            foreach (var proc in running)
            {
                itemsScanned++;
                if (string.IsNullOrWhiteSpace(proc.ExecutablePath)) continue;

                string procPath = proc.ExecutablePath;
                if (!inspectedPaths.Add(procPath)) continue;

                if (IsStagingPath(procPath, stagingDirectories))
                {
                    var sig = _sigValidator.ValidateSignature(procPath);
                    if (!sig.IsValid)
                    {
                        threats.Add(new PersistenceThreatItem
                        {
                            Id = $"running_unsigned_{proc.ProcessName}_{proc.ProcessId}",
                            Category = "Suspicious Running Binary",
                            Name = $"Unsigned Process in Staging: {proc.ProcessName} (PID: {proc.ProcessId})",
                            Location = procPath,
                            CommandOrValue = $"PID: {proc.ProcessId} | Error: {sig.Error ?? "Unsigned"}",
                            Severity = ThreatSeverity.Critical,
                            Description = $"Active process executing from user staging directory without valid Authenticode digital signature ({sig.Error}).",
                            TargetType = "File",
                            AdditionalData = procPath
                        });
                    }
                }
            }

            // 2. Audit staged executable & script files on disk
            var targetExtensions = new[] { "*.exe", "*.dll", "*.bat", "*.vbs", "*.ps1", "*.cmd", "*.js", "*.scr", "*.hta" };
            foreach (var dir in stagingDirectories)
            {
                foreach (var ext in targetExtensions)
                {
                    string[] files;
                    try
                    {
                        files = _fileSystem.GetFiles(dir, ext, SearchOption.TopDirectoryOnly);
                    }
                    catch
                    {
                        continue;
                    }

                    foreach (var f in files)
                    {
                        itemsScanned++;
                        if (!inspectedPaths.Add(f)) continue;

                        long length = _fileSystem.GetFileLength(f);
                        if (length == 0) continue;

                        string extension = Path.GetExtension(f).ToLowerInvariant();
                        bool isScript = extension is ".bat" or ".vbs" or ".ps1" or ".cmd" or ".js" or ".hta";

                        if (isScript)
                        {
                            threats.Add(new PersistenceThreatItem
                            {
                                Id = $"staged_script_{Path.GetFileName(f)}",
                                Category = "Staged Script Payload",
                                Name = Path.GetFileName(f),
                                Location = f,
                                CommandOrValue = $"Size: {length / 1024.0:F1} KB | Extension: {extension}",
                                Severity = ThreatSeverity.Medium,
                                Description = "Script payload staged directly in user temporary execution path.",
                                TargetType = "File",
                                AdditionalData = f
                            });
                        }
                        else
                        {
                            var sig = _sigValidator.ValidateSignature(f);
                            if (!sig.IsValid)
                            {
                                threats.Add(new PersistenceThreatItem
                                {
                                    Id = $"staged_unsigned_{Path.GetFileName(f)}",
                                    Category = "Unsigned Staged Binary",
                                    Name = Path.GetFileName(f),
                                    Location = f,
                                    CommandOrValue = $"Size: {length / 1024.0:F1} KB | Status: {sig.Error ?? "Unsigned"}",
                                    Severity = sig.IsSelfSigned ? ThreatSeverity.High : ThreatSeverity.Medium,
                                    Description = $"Binary in staging directory lacks valid trusted digital signature ({sig.Error}).",
                                    TargetType = "File",
                                    AdditionalData = f
                                });
                            }
                        }
                    }
                }
            }

            return threats;
        }

        private static bool IsStagingPath(string path, List<string> stagingDirs)
        {
            string lower = path.ToLowerInvariant();
            if (lower.Contains(@"\appdata\") || lower.Contains(@"\temp\") || lower.Contains(@"\programdata\") || lower.Contains(@"c:\users\public\"))
            {
                return true;
            }

            foreach (var dir in stagingDirs)
            {
                if (path.StartsWith(dir, StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }
            return false;
        }

