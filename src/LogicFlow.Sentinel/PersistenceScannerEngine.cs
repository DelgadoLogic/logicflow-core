    /// <summary>
    /// Default Authenticode digital signature validator utilizing X509Certificate2 and Win32 WinVerifyTrust.
    /// </summary>
    public class WindowsDigitalSignatureValidator : IDigitalSignatureValidator
    {
        [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
        private struct WINTRUST_FILE_INFO
        {
            public uint cbStruct;
            [MarshalAs(UnmanagedType.LPWStr)]
            public string pcwszFilePath;
            public IntPtr hFile;
            public IntPtr pgKnownSubject;
        }

        [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
        private struct WINTRUST_DATA
        {
            public uint cbStruct;
            public IntPtr pPolicyCallbackData;
            public IntPtr pSIPClientData;
            public uint dwUIChoice;
            public uint fdwRevocationChecks;
            public uint dwUnionChoice;
            public IntPtr pFile;
            public uint dwStateAction;
            public IntPtr hWVTStateData;
            [MarshalAs(UnmanagedType.LPWStr)]
            public string pwszURLReference;
            public uint dwProvFlags;
            public uint dwUIContext;
            public IntPtr pSignatureSettings;
        }

        private static readonly Guid WINTRUST_ACTION_GENERIC_VERIFY_V2 = new("{00AAC56B-CD44-11d0-8CC2-00C04FC295EE}");

        [DllImport("wintrust.dll", ExactSpelling = true, SetLastError = false, CharSet = CharSet.Unicode)]
        private static extern int WinVerifyTrust(
            IntPtr hwnd,
            [MarshalAs(UnmanagedType.LPStruct)] Guid pgActionID,
            IntPtr pWVTData);

        public SignatureValidationResult ValidateSignature(string filePath)
        {
            if (!File.Exists(filePath))
            {
                return SignatureValidationResult.Unsigned();
            }

            // 1. Check with Win32 WinVerifyTrust
            try
            {
                var fileInfo = new WINTRUST_FILE_INFO
                {
                    cbStruct = (uint)Marshal.SizeOf<WINTRUST_FILE_INFO>(),
                    pcwszFilePath = filePath,
                    hFile = IntPtr.Zero,
                    pgKnownSubject = IntPtr.Zero
                };

                IntPtr pFileInfo = Marshal.AllocHGlobal((int)fileInfo.cbStruct);
                Marshal.StructureToPtr(fileInfo, pFileInfo, false);

                var winTrustData = new WINTRUST_DATA
                {
                    cbStruct = (uint)Marshal.SizeOf<WINTRUST_DATA>(),
                    pPolicyCallbackData = IntPtr.Zero,
                    pSIPClientData = IntPtr.Zero,
                    dwUIChoice = 2, // WTD_UI_NONE
                    fdwRevocationChecks = 0, // WTD_REVOKE_NONE
                    dwUnionChoice = 1, // WTD_CHOICE_FILE
                    pFile = pFileInfo,
                    dwStateAction = 0, // WTD_STATEACTION_IGNORE
                    hWVTStateData = IntPtr.Zero,
                    pwszURLReference = null!,
                    dwProvFlags = 0x00000040 | 0x00000080, // WTD_CACHE_ONLY_URL_RETRIEVAL | WTD_REVOCATION_CHECK_NONE
                    dwUIContext = 0,
                    pSignatureSettings = IntPtr.Zero
                };

                IntPtr pWinTrustData = Marshal.AllocHGlobal((int)winTrustData.cbStruct);
                Marshal.StructureToPtr(winTrustData, pWinTrustData, false);

                int result = WinVerifyTrust(new IntPtr(-1), WINTRUST_ACTION_GENERIC_VERIFY_V2, pWinTrustData);

                Marshal.FreeHGlobal(pFileInfo);
                Marshal.FreeHGlobal(pWinTrustData);

                if (result == 0) // ERROR_SUCCESS
                {
                    // Valid Authenticode signature
                    try
                    {
                        using var cert = new X509Certificate2(X509Certificate.CreateFromSignedFile(filePath));
                        return SignatureValidationResult.Valid(cert.GetNameInfo(X509NameType.SimpleName, false), cert.Issuer, cert.NotAfter);
                    }
                    catch
                    {
                        return SignatureValidationResult.Valid("Verified Publisher", "Trusted Root", DateTime.MaxValue);
                    }
                }
            }
            catch { }

            // 2. Managed X509 fallback check
            try
            {
                using var cert = new X509Certificate2(X509Certificate.CreateFromSignedFile(filePath));
                bool isSelfSigned = string.Equals(cert.Subject, cert.Issuer, StringComparison.OrdinalIgnoreCase);
                bool isExpired = DateTime.Now > cert.NotAfter;

                using var chain = new X509Chain();
                chain.ChainPolicy.RevocationMode = X509RevocationMode.NoCheck;
                bool chainValid = chain.Build(cert);

                string signer = cert.GetNameInfo(X509NameType.SimpleName, false) ?? cert.Subject;

                if (chainValid && !isExpired && !isSelfSigned)
                {
                    return SignatureValidationResult.Valid(signer, cert.Issuer, cert.NotAfter);
                }

                return SignatureValidationResult.Invalid(
                    isSelfSigned ? "Self-signed certificate." : (isExpired ? "Certificate expired." : "Untrusted certificate chain."),
                    selfSigned: isSelfSigned,
                    expired: isExpired,
                    signer: signer);
            }
            catch
            {
                return SignatureValidationResult.Unsigned();
            }
        }
    }

