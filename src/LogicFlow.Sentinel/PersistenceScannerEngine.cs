        public async Task<PersistenceScanReport> ScanAsync(CancellationToken ct = default)
        {
            return await Task.Run(async () =>
            {
                var report = new PersistenceScanReport();
                int itemsScanned = 0;

                // 1. Audit WMI Event Subscriptions
                try
                {
                    var wmiThreats = AuditWmiSubscriptions(ref itemsScanned, report);
                    report.Threats.AddRange(wmiThreats);
                }
                catch (UnauthorizedAccessException uex)
                {
                    report.RequiresElevation = true;
                    _logger?.LogWarning(uex, "WMI subscription audit requires elevation.");
                }
                catch (Exception ex)
                {
                    _logger?.LogWarning(ex, "WMI subscription audit encountered a non-critical error.");
                }

                // 2. Audit Scheduled Tasks & LOLBAS Triggers
                try
                {
                    var taskThreats = await AuditScheduledTasksAsync(report, ct).ConfigureAwait(false);
                    report.Threats.AddRange(taskThreats);
                }
                catch (UnauthorizedAccessException uex)
                {
                    report.RequiresElevation = true;
                    _logger?.LogWarning(uex, "Scheduled tasks audit requires elevation.");
                }
                catch (Exception ex)
                {
                    _logger?.LogWarning(ex, "Scheduled tasks audit encountered a non-critical error.");
                }

                // 3. Audit Image File Execution Options (IFEO), AppInit, and Winlogon
                try
                {
                    var ifeoThreats = AuditIfeoAppInitAndWinlogon(ref itemsScanned, report);
                    report.Threats.AddRange(ifeoThreats);
                }
                catch (UnauthorizedAccessException uex)
                {
                    report.RequiresElevation = true;
                    _logger?.LogWarning(uex, "IFEO/AppInit audit requires elevation.");
                }
                catch (Exception ex)
                {
                    _logger?.LogWarning(ex, "IFEO/AppInit audit encountered a non-critical error.");
                }

                // 4. Audit Unsigned Temp/AppData/ProgramData Staged & Running Executables
                try
                {
                    var tempThreats = AuditStagedAndRunningBinaries(ref itemsScanned);
                    report.Threats.AddRange(tempThreats);
                }
                catch (Exception ex)
                {
                    _logger?.LogWarning(ex, "Binaries audit encountered a non-critical error.");
                }

                report.TotalItemsScanned = itemsScanned;
                return report;
            }, ct).ConfigureAwait(false);
        }

        #region Vector 1: WMI Subscriptions

        private List<PersistenceThreatItem> AuditWmiSubscriptions(ref int itemsScanned, PersistenceScanReport report)
        {
            var threats = new List<PersistenceThreatItem>();
            List<WmiEventConsumerInfo> consumers;
            List<WmiEventFilterInfo> filters;
            List<WmiBindingInfo> bindings;

            try
            {
                consumers = _wmiService.GetConsumers();
                filters = _wmiService.GetFilters();
                bindings = _wmiService.GetBindings();
            }
            catch (UnauthorizedAccessException)
            {
                report.RequiresElevation = true;
                return threats;
            }
            catch
            {
                return threats;
            }

            itemsScanned += consumers.Count + filters.Count + bindings.Count;

            var boundConsumerNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var boundFilterNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            // 1. Audit active bindings
            foreach (var binding in bindings)
            {
                boundConsumerNames.Add(binding.ConsumerName);
                boundFilterNames.Add(binding.FilterName);

                if (BenignWmiWhitelist.Contains(binding.ConsumerName) || BenignWmiWhitelist.Contains(binding.FilterName))
                {
                    continue;
                }

                var matchedConsumer = consumers.FirstOrDefault(c => string.Equals(c.Name, binding.ConsumerName, StringComparison.OrdinalIgnoreCase));
                var matchedFilter = filters.FirstOrDefault(f => string.Equals(f.Name, binding.FilterName, StringComparison.OrdinalIgnoreCase));

                string command = matchedConsumer?.CommandLineTemplate ?? matchedConsumer?.ScriptText ?? matchedConsumer?.ScriptFileName ?? "Active Binding";
                bool isEncoded = command.Contains("-enc", StringComparison.OrdinalIgnoreCase) || command.Contains("-e ", StringComparison.OrdinalIgnoreCase);

                threats.Add(new PersistenceThreatItem
                {
                    Id = $"wmi_binding_{binding.ConsumerName}_{binding.FilterName}",
                    Category = "WMI Persistence",
                    Name = $"WMI Subscription: {binding.ConsumerName}",
                    Location = @"root\subscription",
                    CommandOrValue = command,
                    Severity = isEncoded ? ThreatSeverity.Critical : ThreatSeverity.High,
                    Description = $"Active WMI Event Subscription binding filter '{binding.FilterName}' ({matchedFilter?.Query}) to consumer '{binding.ConsumerName}'.",
                    TargetType = "WMI",
                    AdditionalData = $"{binding.ConsumerName}|{binding.FilterName}"
                });
            }

            // 2. Audit orphaned consumers
            foreach (var consumer in consumers)
            {
                if (BenignWmiWhitelist.Contains(consumer.Name)) continue;
                if (boundConsumerNames.Contains(consumer.Name)) continue;

                string? command = consumer.CommandLineTemplate ?? consumer.ScriptText ?? consumer.ScriptFileName;
                if (!string.IsNullOrWhiteSpace(command))
                {
                    threats.Add(new PersistenceThreatItem
                    {
                        Id = $"wmi_consumer_{consumer.Name}",
                        Category = "WMI Persistence",
                        Name = $"Orphaned WMI Consumer: {consumer.Name}",
                        Location = @"root\subscription",
                        CommandOrValue = command,
                        Severity = ThreatSeverity.High,
                        Description = $"Orphaned WMI Event Consumer ({consumer.ConsumerType}) containing standalone execution payload.",
                        TargetType = "WMI",
                        AdditionalData = consumer.Name
                    });
                }
            }

            // 3. Audit orphaned custom filters
            foreach (var filter in filters)
            {
                if (BenignWmiWhitelist.Contains(filter.Name)) continue;
                if (boundFilterNames.Contains(filter.Name)) continue;

                threats.Add(new PersistenceThreatItem
                {
                    Id = $"wmi_filter_{filter.Name}",
                    Category = "WMI Persistence",
                    Name = $"Orphaned WMI Filter: {filter.Name}",
                    Location = @"root\subscription",
                    CommandOrValue = filter.Query,
                    Severity = ThreatSeverity.Low,
                    Description = $"Orphaned WMI Event Filter triggering on query: {filter.Query}",
                    TargetType = "WMI",
                    AdditionalData = filter.Name
                });
            }

            return threats;
        }

        #endregion

        #region Vector 2: Scheduled Tasks & LOLBAS

        private async Task<List<PersistenceThreatItem>> AuditScheduledTasksAsync(PersistenceScanReport report, CancellationToken ct)
        {
            var threats = new List<PersistenceThreatItem>();
            List<ScheduledTaskInfo> tasks;

            try
            {
                tasks = await _taskService.QueryTasksAsync(ct).ConfigureAwait(false);
            }
            catch (UnauthorizedAccessException)
            {
                report.RequiresElevation = true;
                return threats;
            }
            catch
            {
                return threats;
            }

            report.TotalItemsScanned += tasks.Count;

            foreach (var task in tasks)
            {
                // Check for GhostTask tampering (missing Security Descriptor)
                if (!task.HasSecurityDescriptor)
                {
                    threats.Add(new PersistenceThreatItem
                    {
                        Id = $"task_ghost_{task.TaskName.Replace('\\', '_')}",
                        Category = "Ghost Scheduled Task",
                        Name = $"Ghost Task: {task.TaskName}",
                        Location = $@"TaskCache\Tree{task.TaskName}",
                        CommandOrValue = task.TaskToRun,
                        Severity = ThreatSeverity.Critical,
                        Description = "Tampered Scheduled Task with missing Security Descriptor (SD) in registry to evade standard management utilities.",
                        TargetType = "Task",
                        AdditionalData = task.TaskName
                    });
                    continue;
                }

                if (string.IsNullOrWhiteSpace(task.TaskToRun)) continue;

                string action = task.TaskToRun.Trim();
                string lowerAction = action.ToLowerInvariant();

                // 1. Check for Encoded PowerShell commands
                var encMatch = Regex.Match(action, @"(?:-e|-enc|-encodedcommand)\s+([A-Za-z0-9+/=]{12,})", RegexOptions.IgnoreCase);
                if (encMatch.Success)
                {
                    string b64 = encMatch.Groups[1].Value;
                    string decoded = "";
                    bool isHighCritical = false;

                    try
                    {
                        byte[] bytes = Convert.FromBase64String(b64);
                        decoded = Encoding.Unicode.GetString(bytes);
                        string lowerDecoded = decoded.ToLowerInvariant();

                        isHighCritical = lowerDecoded.Contains("downloadstring") ||
                                         lowerDecoded.Contains("webclient") ||
                                         lowerDecoded.Contains("iex") ||
                                         lowerDecoded.Contains("invoke-expression") ||
                                         lowerDecoded.Contains("bypass") ||
                                         lowerDecoded.Contains("hidden") ||
                                         lowerDecoded.Contains("disable");
                    }
                    catch { }

                    threats.Add(new PersistenceThreatItem
                    {
                        Id = $"task_enc_ps_{task.TaskName.Replace('\\', '_')}",
                        Category = "LOLBAS Scheduled Task",
                        Name = $"Encoded PowerShell Task: {task.TaskName}",
                        Location = task.TaskName,
                        CommandOrValue = string.IsNullOrEmpty(decoded) ? action : $"Decoded: {decoded}",
                        Severity = isHighCritical ? ThreatSeverity.Critical : ThreatSeverity.High,
                        Description = isHighCritical
                            ? "Scheduled Task executing Base64 encoded PowerShell download cradle / payload."
                            : "Scheduled Task executing Base64 encoded PowerShell command.",
                        TargetType = "Task",
                        AdditionalData = task.TaskName
                    });
                    continue;
                }

                // 2. Check for LOLBAS binaries and hidden parameters
                bool isLolbas = false;
                string matchedTool = "";
                foreach (var sig in LolbasSignatures)
                {
                    if (lowerAction.Contains(sig))
                    {
                        if (sig == "powershell" && (lowerAction.Contains("-w hidden") || lowerAction.Contains("-windowstyle hidden") || lowerAction.Contains("-nop") || lowerAction.Contains("-noprofile")))
                        {
                            isLolbas = true;
                            matchedTool = "powershell (hidden)";
                            break;
                        }
                        else if (sig != "powershell")
                        {
                            isLolbas = true;
                            matchedTool = sig;
                            break;
                        }
                    }
                }

                if (isLolbas)
                {
                    threats.Add(new PersistenceThreatItem
                    {
                        Id = $"task_lolbas_{task.TaskName.Replace('\\', '_')}",
                        Category = "LOLBAS Scheduled Task",
                        Name = $"LOLBAS Trigger ({matchedTool}): {task.TaskName}",
                        Location = task.TaskName,
                        CommandOrValue = action,
                        Severity = ThreatSeverity.High,
                        Description = $"Scheduled Task utilizes LOLBAS tool ({matchedTool}) to trigger execution.",
                        TargetType = "Task",
                        AdditionalData = task.TaskName
                    });
                    continue;
                }

                // 3. Check for Unquoted Executable Paths in User Space (CWE-428)
                if (IsUnquotedUserPath(action))
                {
                    threats.Add(new PersistenceThreatItem
                    {
                        Id = $"task_unquoted_{task.TaskName.Replace('\\', '_')}",
                        Category = "Vulnerable Scheduled Task",
                        Name = $"Unquoted Path in User Space: {task.TaskName}",
                        Location = task.TaskName,
                        CommandOrValue = action,
                        Severity = ThreatSeverity.High,
                        Description = "Scheduled Task contains an unquoted executable path with spaces in user-writable directory (CWE-428 privilege escalation vector).",
                        TargetType = "Task",
                        AdditionalData = task.TaskName
                    });
                }
            }

            return threats;
        }

        private static bool IsUnquotedUserPath(string command)
        {
            if (string.IsNullOrWhiteSpace(command) || command.StartsWith('"')) return false;

            string lower = command.ToLowerInvariant();
            bool isUserSpace = lower.Contains(@"\appdata\") ||
                               lower.Contains(@"\temp\") ||
                               lower.Contains(@"\users\") ||
                               lower.Contains(@"\programdata\");

            if (!isUserSpace) return false;

            int exeIdx = lower.IndexOf(".exe", StringComparison.Ordinal);
            if (exeIdx > 0)
            {
                string pathPart = command.Substring(0, exeIdx + 4);
                return pathPart.Contains(' ') && !pathPart.StartsWith('"');
            }

            return false;
        }

