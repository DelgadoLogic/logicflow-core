    /// <summary>
    /// Default live Windows Registry service supporting 64-bit and 32-bit views.
    /// </summary>
    public class WindowsPersistenceRegistryService : IPersistenceRegistryService
    {
        public int? GetDword(RegistryHive hive, RegistryView view, string subKey, string valueName)
        {
            try
            {
                using var baseKey = RegistryKey.OpenBaseKey(hive, view);
                using var key = baseKey.OpenSubKey(subKey);
                var raw = key?.GetValue(valueName);
                if (raw is int i) return i;
                if (raw is string s && int.TryParse(s, out var parsed)) return parsed;
                return null;
            }
            catch
            {
                return null;
            }
        }

        public string? GetString(RegistryHive hive, RegistryView view, string subKey, string valueName)
        {
            try
            {
                using var baseKey = RegistryKey.OpenBaseKey(hive, view);
                using var key = baseKey.OpenSubKey(subKey);
                return key?.GetValue(valueName) as string;
            }
            catch
            {
                return null;
            }
        }

        public void SetDword(RegistryHive hive, RegistryView view, string subKey, string valueName, int value)
        {
            using var baseKey = RegistryKey.OpenBaseKey(hive, view);
            using var key = baseKey.CreateSubKey(subKey, true);
            key.SetValue(valueName, value, RegistryValueKind.DWord);
        }

        public void SetString(RegistryHive hive, RegistryView view, string subKey, string valueName, string value)
        {
            using var baseKey = RegistryKey.OpenBaseKey(hive, view);
            using var key = baseKey.CreateSubKey(subKey, true);
            key.SetValue(valueName, value, RegistryValueKind.String);
        }

        public void DeleteValue(RegistryHive hive, RegistryView view, string subKey, string valueName)
        {
            using var baseKey = RegistryKey.OpenBaseKey(hive, view);
            using var key = baseKey.OpenSubKey(subKey, true);
            key?.DeleteValue(valueName, false);
        }

        public void DeleteSubKeyTree(RegistryHive hive, RegistryView view, string subKey)
        {
            using var baseKey = RegistryKey.OpenBaseKey(hive, view);
            baseKey.DeleteSubKeyTree(subKey, false);
        }

        public string[] GetSubKeyNames(RegistryHive hive, RegistryView view, string subKey)
        {
            try
            {
                using var baseKey = RegistryKey.OpenBaseKey(hive, view);
                using var key = baseKey.OpenSubKey(subKey);
                return key?.GetSubKeyNames() ?? Array.Empty<string>();
            }
            catch
            {
                return Array.Empty<string>();
            }
        }

        public IReadOnlyDictionary<string, object> GetValues(RegistryHive hive, RegistryView view, string subKey)
        {
            var dict = new Dictionary<string, object>(StringComparer.OrdinalIgnoreCase);
            try
            {
                using var baseKey = RegistryKey.OpenBaseKey(hive, view);
                using var key = baseKey.OpenSubKey(subKey);
                if (key != null)
                {
                    foreach (var name in key.GetValueNames())
                    {
                        var val = key.GetValue(name);
                        if (val != null) dict[name] = val;
                    }
                }
            }
            catch { }
            return dict;
        }
    }

    /// <summary>
    /// Default live WMI subscription provider querying root\subscription.
    /// </summary>
    public class WindowsWmiSubscriptionService : IWmiSubscriptionService
    {
        private const string ScopePath = @"\\.\root\subscription";

        public List<WmiEventConsumerInfo> GetConsumers()
        {
            var consumers = new List<WmiEventConsumerInfo>();
            try
            {
                var scope = new ManagementScope(ScopePath);
                scope.Connect();

                using var searcher = new ManagementObjectSearcher(scope, new ObjectQuery("SELECT * FROM __EventConsumer"));
                foreach (ManagementObject obj in searcher.Get())
                {
                    string name = obj["Name"]?.ToString() ?? "Unknown";
                    string type = obj.ClassPath?.ClassName ?? "__EventConsumer";
                    consumers.Add(new WmiEventConsumerInfo
                    {
                        Name = name,
                        ConsumerType = type,
                        CommandLineTemplate = obj["CommandLineTemplate"]?.ToString(),
                        ExecutablePath = obj["ExecutablePath"]?.ToString(),
                        ScriptText = obj["ScriptText"]?.ToString(),
                        ScriptFileName = obj["ScriptFileName"]?.ToString(),
                        ScriptingEngine = obj["ScriptingEngine"]?.ToString(),
                        RawObjectPath = obj.Path?.Path ?? ""
                    });
                }
            }
            catch (ManagementException mex)
            {
                throw new UnauthorizedAccessException($"WMI query failed: {mex.Message} (Status: {mex.ErrorCode})", mex);
            }
            catch (Exception ex)
            {
                throw new UnauthorizedAccessException($"WMI connection failed: {ex.Message}", ex);
            }
            return consumers;
        }

        public List<WmiEventFilterInfo> GetFilters()
        {
            var filters = new List<WmiEventFilterInfo>();
            try
            {
                var scope = new ManagementScope(ScopePath);
                scope.Connect();

                using var searcher = new ManagementObjectSearcher(scope, new ObjectQuery("SELECT * FROM __EventFilter"));
                foreach (ManagementObject obj in searcher.Get())
                {
                    string name = obj["Name"]?.ToString() ?? "Unknown";
                    string query = obj["Query"]?.ToString() ?? "";
                    string queryLanguage = obj["QueryLanguage"]?.ToString() ?? "WQL";
                    string eventNamespace = obj["EventNamespace"]?.ToString() ?? @"root\cimv2";

                    filters.Add(new WmiEventFilterInfo
                    {
                        Name = name,
                        Query = query,
                        QueryLanguage = queryLanguage,
                        EventNamespace = eventNamespace,
                        RawObjectPath = obj.Path?.Path ?? ""
                    });
                }
            }
            catch (ManagementException mex)
            {
                throw new UnauthorizedAccessException($"WMI query failed: {mex.Message} (Status: {mex.ErrorCode})", mex);
            }
            catch (Exception ex)
            {
                throw new UnauthorizedAccessException($"WMI connection failed: {ex.Message}", ex);
            }
            return filters;
        }

        public List<WmiBindingInfo> GetBindings()
        {
            var bindings = new List<WmiBindingInfo>();
            try
            {
                var scope = new ManagementScope(ScopePath);
                scope.Connect();

                using var searcher = new ManagementObjectSearcher(scope, new ObjectQuery("SELECT * FROM __FilterToConsumerBinding"));
                foreach (ManagementObject obj in searcher.Get())
                {
                    string consumerPath = obj["Consumer"]?.ToString() ?? "";
                    string filterPath = obj["Filter"]?.ToString() ?? "";

                    string consumerName = ExtractWmiNameFromPath(consumerPath);
                    string filterName = ExtractWmiNameFromPath(filterPath);

                    bindings.Add(new WmiBindingInfo
                    {
                        ConsumerPath = consumerPath,
                        FilterPath = filterPath,
                        ConsumerName = consumerName,
                        FilterName = filterName,
                        RawObjectPath = obj.Path?.Path ?? ""
                    });
                }
            }
            catch (ManagementException mex)
            {
                throw new UnauthorizedAccessException($"WMI query failed: {mex.Message} (Status: {mex.ErrorCode})", mex);
            }
            catch (Exception ex)
            {
                throw new UnauthorizedAccessException($"WMI connection failed: {ex.Message}", ex);
            }
            return bindings;
        }

        public void DeleteBinding(string consumerName, string filterName)
        {
            var scope = new ManagementScope(ScopePath);
            scope.Connect();

            using var searcher = new ManagementObjectSearcher(scope, new ObjectQuery("SELECT * FROM __FilterToConsumerBinding"));
            foreach (ManagementObject obj in searcher.Get())
            {
                string cPath = obj["Consumer"]?.ToString() ?? "";
                string fPath = obj["Filter"]?.ToString() ?? "";
                if (cPath.Contains(consumerName, StringComparison.OrdinalIgnoreCase) &&
                    fPath.Contains(filterName, StringComparison.OrdinalIgnoreCase))
                {
                    obj.Delete();
                }
            }
        }

        public void DeleteConsumer(string consumerName)
        {
            var scope = new ManagementScope(ScopePath);
            scope.Connect();

            using var searcher = new ManagementObjectSearcher(scope, new ObjectQuery("SELECT * FROM __EventConsumer"));
            foreach (ManagementObject obj in searcher.Get())
            {
                string name = obj["Name"]?.ToString() ?? "";
                if (string.Equals(name, consumerName, StringComparison.OrdinalIgnoreCase))
                {
                    obj.Delete();
                }
            }
        }

        public void DeleteFilter(string filterName)
        {
            var scope = new ManagementScope(ScopePath);
            scope.Connect();

            using var searcher = new ManagementObjectSearcher(scope, new ObjectQuery("SELECT * FROM __EventFilter"));
            foreach (ManagementObject obj in searcher.Get())
            {
                string name = obj["Name"]?.ToString() ?? "";
                if (string.Equals(name, filterName, StringComparison.OrdinalIgnoreCase))
                {
                    obj.Delete();
                }
            }
        }

        private static string ExtractWmiNameFromPath(string path)
        {
            if (string.IsNullOrWhiteSpace(path)) return "";
            var match = Regex.Match(path, @"Name\s*=\s*[""']?([^""',]+)[""']?", RegexOptions.IgnoreCase);
            if (match.Success)
            {
                return match.Groups[1].Value.Trim();
            }
            return path;
        }
    }

    /// <summary>
    /// Default live Scheduled Tasks service parsing schtasks.exe CSV output and TaskCache registry.
    /// </summary>
    public class WindowsScheduledTaskService : IScheduledTaskService
    {
        private readonly IProcessRunner _processRunner;
        private readonly IPersistenceRegistryService _registry;

        public WindowsScheduledTaskService(IProcessRunner? processRunner = null, IPersistenceRegistryService? registry = null)
        {
            _processRunner = processRunner ?? new WindowsProcessRunner();
            _registry = registry ?? new WindowsPersistenceRegistryService();
        }

        public async Task<List<ScheduledTaskInfo>> QueryTasksAsync(CancellationToken ct = default)
        {
            var taskList = new List<ScheduledTaskInfo>();
            var seenNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            // 1. Query schtasks.exe /query /fo csv /v
            try
            {
                var execResult = await _processRunner.RunAsync("schtasks.exe", "/query /fo csv /v", ct).ConfigureAwait(false);
                if (execResult.Success && !string.IsNullOrWhiteSpace(execResult.StandardOutput))
                {
                    var parsedTasks = ParseSchtasksCsv(execResult.StandardOutput);
                    foreach (var t in parsedTasks)
                    {
                        if (seenNames.Add(t.TaskName))
                        {
                            taskList.Add(t);
                        }
                    }
                }
            }
            catch { }

            // 2. Query Registry Fallback & Ghost Tasks in TaskCache\Tree
            try
            {
                const string treePath = @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Schedule\TaskCache\Tree";
                EnumerateRegistryTasks(RegistryHive.LocalMachine, RegistryView.Registry64, treePath, "", taskList, seenNames);
            }
            catch { }

            return taskList;
        }

        public async Task<bool> DeleteTaskAsync(string taskName, CancellationToken ct = default)
        {
            try
            {
                string cleanName = taskName.StartsWith(@"\", StringComparison.Ordinal) ? taskName : @"\" + taskName;
                var result = await _processRunner.RunAsync("schtasks.exe", $"/delete /tn \"{cleanName}\" /f", ct).ConfigureAwait(false);
                if (result.Success) return true;
            }
            catch { }

            // Registry direct deletion fallback
            try
            {
                string relTreePath = @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Schedule\TaskCache\Tree\" + taskName.TrimStart('\\');
                _registry.DeleteSubKeyTree(RegistryHive.LocalMachine, RegistryView.Registry64, relTreePath);
                return true;
            }
            catch
            {
                return false;
            }
        }

        private void EnumerateRegistryTasks(RegistryHive hive, RegistryView view, string rootPath, string subRelative, List<ScheduledTaskInfo> taskList, HashSet<string> seenNames)
        {
            string currentPath = string.IsNullOrEmpty(subRelative) ? rootPath : $"{rootPath}\\{subRelative}";
            var subKeys = _registry.GetSubKeyNames(hive, view, currentPath);

            var values = _registry.GetValues(hive, view, currentPath);
            if (values.TryGetValue("Id", out var idVal))
            {
                string taskGuid = idVal?.ToString() ?? "";
                string taskName = @"\" + subRelative;
                bool hasSd = values.ContainsKey("SD");

                string taskToRun = "";
                if (!string.IsNullOrEmpty(taskGuid))
                {
                    string taskDetailPath = $@"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Schedule\TaskCache\Tasks\{taskGuid}";
                    var taskValues = _registry.GetValues(hive, view, taskDetailPath);
                    if (taskValues.TryGetValue("Actions", out var actionsVal))
                    {
                        taskToRun = actionsVal?.ToString() ?? "";
                    }
                }

                if (seenNames.Add(taskName))
                {
                    taskList.Add(new ScheduledTaskInfo
                    {
                        TaskName = taskName,
                        TaskToRun = taskToRun,
                        Author = values.TryGetValue("Author", out var a) ? a?.ToString() ?? "" : "",
                        Status = "Ready",
                        HasSecurityDescriptor = hasSd,
                        TaskGuid = taskGuid
                    });
                }
                else if (!hasSd)
                {
                    // Existing task discovered from schtasks missing SD in registry (GhostTask flag)
                    var existing = taskList.FirstOrDefault(t => string.Equals(t.TaskName, taskName, StringComparison.OrdinalIgnoreCase));
                    if (existing != null)
                    {
                        taskList.Remove(existing);
                        taskList.Add(new ScheduledTaskInfo
                        {
                            TaskName = existing.TaskName,
                            TaskToRun = existing.TaskToRun,
                            Author = existing.Author,
                            Status = existing.Status,
                            IsHidden = existing.IsHidden,
                            HasSecurityDescriptor = false,
                            TaskGuid = taskGuid
                        });
                    }
                }
            }

            foreach (var sub in subKeys)
            {
                string nextRelative = string.IsNullOrEmpty(subRelative) ? sub : $"{subRelative}\\{sub}";
                EnumerateRegistryTasks(hive, view, rootPath, nextRelative, taskList, seenNames);
            }
        }

        public static List<ScheduledTaskInfo> ParseSchtasksCsv(string csvContent)
        {
            var result = new List<ScheduledTaskInfo>();
            var records = CsvParser.ParseCsv(csvContent);
            if (records.Count < 2) return result;

            var headers = records[0].Select(h => h.Trim().ToLowerInvariant()).ToList();

            // Dynamic header detection supporting multilingual Windows editions
            int taskNameIdx = FindColumnIndex(headers, "taskname", "nom de la tâche", "nombre de la tarea", "aufgabenname", "nome tarefa", "name");
            int taskToRunIdx = FindColumnIndex(headers, "task to run", "tarea a ejecutar", "action", "auszuführende aufgabe", "commande", "comando", "to run");
            int authorIdx = FindColumnIndex(headers, "author", "autor", "créateur", "auteur");
            int statusIdx = FindColumnIndex(headers, "status", "estado", "statut");

            if (taskNameIdx < 0) taskNameIdx = 0;
            if (taskToRunIdx < 0) taskToRunIdx = headers.Count > 8 ? 8 : (headers.Count > 1 ? 1 : 0);

            for (int r = 1; r < records.Count; r++)
            {
                var row = records[r];
                if (row.Count <= taskNameIdx) continue;

                string name = row[taskNameIdx].Trim();
                if (string.IsNullOrWhiteSpace(name)) continue;

                string toRun = taskToRunIdx >= 0 && taskToRunIdx < row.Count ? row[taskToRunIdx].Trim() : "";
                string author = authorIdx >= 0 && authorIdx < row.Count ? row[authorIdx].Trim() : "";
                string status = statusIdx >= 0 && statusIdx < row.Count ? row[statusIdx].Trim() : "";

                result.Add(new ScheduledTaskInfo
                {
                    TaskName = name,
                    TaskToRun = toRun,
                    Author = author,
                    Status = status,
                    HasSecurityDescriptor = true
                });
            }

            return result;
        }

        private static int FindColumnIndex(List<string> headers, params string[] patterns)
        {
            for (int i = 0; i < headers.Count; i++)
            {
                foreach (var p in patterns)
                {
                    if (headers[i].Contains(p, StringComparison.OrdinalIgnoreCase))
                    {
                        return i;
                    }
                }
            }
            return -1;
        }
    }

    /// <summary>
    /// RFC-4180 streaming CSV parser for handling embedded quotes, newlines, and commas.
    /// </summary>
    public static class CsvParser
    {
        public static List<List<string>> ParseCsv(string csvText)
        {
            var records = new List<List<string>>();
            if (string.IsNullOrWhiteSpace(csvText)) return records;

            var currentRecord = new List<string>();
            var currentField = new StringBuilder();
            bool inQuotes = false;
            int i = 0;

            while (i < csvText.Length)
            {
                char c = csvText[i];

                if (c == '"')
                {
                    if (inQuotes && i + 1 < csvText.Length && csvText[i + 1] == '"')
                    {
                        currentField.Append('"');
                        i += 2;
                        continue;
                    }
                    inQuotes = !inQuotes;
                    i++;
                }
                else if (c == ',' && !inQuotes)
                {
                    currentRecord.Add(currentField.ToString());
                    currentField.Clear();
                    i++;
                }
                else if ((c == '\r' || c == '\n') && !inQuotes)
                {
                    if (c == '\r' && i + 1 < csvText.Length && csvText[i + 1] == '\n')
                    {
                        i++;
                    }
                    currentRecord.Add(currentField.ToString());
                    currentField.Clear();
                    if (currentRecord.Count > 1 || (currentRecord.Count == 1 && !string.IsNullOrWhiteSpace(currentRecord[0])))
                    {
                        records.Add(currentRecord);
                    }
                    currentRecord = new List<string>();
                    i++;
                }
                else
                {
                    currentField.Append(c);
                    i++;
                }
            }

            if (currentField.Length > 0 || currentRecord.Count > 0)
            {
                currentRecord.Add(currentField.ToString());
                if (currentRecord.Count > 1 || (currentRecord.Count == 1 && !string.IsNullOrWhiteSpace(currentRecord[0])))
                {
                    records.Add(currentRecord);
                }
            }

            return records;
        }
    }

