        #region Remediation Engine

        public async Task<PersistenceRemediationResult> RemediateEntryAsync(PersistenceEntry entry, CancellationToken ct = default)
        {
            return await RemediateInternalAsync(entry, ct).ConfigureAwait(false);
        }

        public async Task<PersistenceRemediationResult> RemediateEntryAsync(PersistenceThreatItem threat, CancellationToken ct = default)
        {
            return await RemediateInternalAsync(new PersistenceEntry(threat), ct).ConfigureAwait(false);
        }

        public async Task<List<PersistenceRemediationResult>> RemediateAllAsync(IEnumerable<PersistenceThreatItem> threats, CancellationToken ct = default)
        {
            var results = new List<PersistenceRemediationResult>();
            foreach (var t in threats)
            {
                results.Add(await RemediateEntryAsync(t, ct).ConfigureAwait(false));
            }
            return results;
        }

        private async Task<PersistenceRemediationResult> RemediateInternalAsync(PersistenceEntry entry, CancellationToken ct)
        {
            if (!entry.CanRemediate)
            {
                return PersistenceRemediationResult.Fail(entry.Id, "Remediate", "Entry is marked as non-remediable.");
            }

            try
            {
                // 1. WMI Subscriptions Cascade Remediation
                if (entry.TargetType == "WMI" || entry.Category.Contains("WMI", StringComparison.OrdinalIgnoreCase))
                {
                    string data = entry.AdditionalData ?? entry.Name;
                    var parts = data.Split('|');
                    string consumerName = parts[0].Trim();
                    string filterName = parts.Length > 1 ? parts[1].Trim() : "";

                    if (BenignWmiWhitelist.Contains(consumerName) || BenignWmiWhitelist.Contains(filterName))
                    {
                        return PersistenceRemediationResult.Fail(entry.Id, "RemediateWmi", "Cannot remediate protected Windows system WMI subscription.");
                    }

                    // Cascade step 1: Delete binding
                    if (!string.IsNullOrEmpty(consumerName) && !string.IsNullOrEmpty(filterName))
                    {
                        _wmiService.DeleteBinding(consumerName, filterName);
                    }

                    // Cascade step 2: Check remaining bindings and delete consumer
                    if (!string.IsNullOrEmpty(consumerName))
                    {
                        _wmiService.DeleteConsumer(consumerName);
                    }

                    // Cascade step 3: Delete non-system filter if specified
                    if (!string.IsNullOrEmpty(filterName) && !BenignWmiWhitelist.Contains(filterName))
                    {
                        _wmiService.DeleteFilter(filterName);
                    }

                    _logger?.LogInformation("Remediated WMI subscription: {Consumer} / {Filter}", consumerName, filterName);
                    return PersistenceRemediationResult.Ok(entry.Id, "RemediateWmi", $"Safely cascade-deleted WMI binding, consumer '{consumerName}', and associated filter.");
                }

                // 2. Scheduled Tasks Remediation
                if (entry.TargetType == "Task" || entry.Category.Contains("Task", StringComparison.OrdinalIgnoreCase))
                {
                    string taskName = entry.AdditionalData ?? entry.Location;
                    if (string.IsNullOrWhiteSpace(taskName)) taskName = entry.Name;

                    if (taskName.StartsWith(@"\Microsoft\Windows\", StringComparison.OrdinalIgnoreCase))
                    {
                        return PersistenceRemediationResult.Fail(entry.Id, "RemediateTask", "Cannot delete protected Windows core scheduled task.");
                    }

                    bool deleted = await _taskService.DeleteTaskAsync(taskName, ct).ConfigureAwait(false);
                    if (deleted)
                    {
                        _logger?.LogInformation("Deleted scheduled task: {TaskName}", taskName);
                        return PersistenceRemediationResult.Ok(entry.Id, "RemediateTask", $"Successfully deleted scheduled task '{taskName}'.");
                    }
                    return PersistenceRemediationResult.Fail(entry.Id, "RemediateTask", $"Failed to delete scheduled task '{taskName}'.", requiresElevation: true);
                }

                // 3. IFEO Debugger & SilentProcessExit Remediation
                if (entry.TargetType == "IFEO" || entry.Category.Contains("IFEO", StringComparison.OrdinalIgnoreCase) || entry.Category.Contains("SilentProcessExit", StringComparison.OrdinalIgnoreCase))
                {
                    string data = entry.AdditionalData ?? entry.Name;
                    var parts = data.Split('|');
                    string subName = parts[0].Trim();
                    string ifeoPath = $@"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options\{subName}";
                    string silentPath = $@"SOFTWARE\Microsoft\Windows NT\CurrentVersion\SilentProcessExit\{subName}";

                    // Clean across both 64-bit and 32-bit registry views
                    foreach (var view in new[] { RegistryView.Registry64, RegistryView.Registry32 })
                    {
                        _registry.DeleteValue(RegistryHive.LocalMachine, view, ifeoPath, "Debugger");
                        _registry.DeleteValue(RegistryHive.LocalMachine, view, ifeoPath, "GlobalFlag");
                        _registry.DeleteSubKeyTree(RegistryHive.LocalMachine, view, silentPath);
                    }

                    _logger?.LogInformation("Remediated IFEO hook on: {SubName}", subName);
                    return PersistenceRemediationResult.Ok(entry.Id, "RemediateIfeo", $"Removed malicious Debugger and SilentProcessExit hooks for '{subName}'.");
                }

                // 4. AppInit_DLLs Remediation
                if (entry.TargetType == "AppInit" || entry.Category.Contains("AppInit", StringComparison.OrdinalIgnoreCase) || entry.Category.Contains("DLL Injection", StringComparison.OrdinalIgnoreCase))
                {
                    string winPath = @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Windows";
                    foreach (var view in new[] { RegistryView.Registry64, RegistryView.Registry32 })
                    {
                        _registry.SetString(RegistryHive.LocalMachine, view, winPath, "AppInit_DLLs", "");
                        _registry.SetDword(RegistryHive.LocalMachine, view, winPath, "LoadAppInit_DLLs", 0);
                    }

                    _logger?.LogInformation("Cleared AppInit_DLLs and disabled LoadAppInit_DLLs.");
                    return PersistenceRemediationResult.Ok(entry.Id, "RemediateAppInit", "Cleared AppInit_DLLs and disabled LoadAppInit_DLLs (0).");
                }

                // 5. Winlogon Shell & Userinit Remediation
                if (entry.TargetType == "Winlogon" || entry.Category.Contains("Winlogon", StringComparison.OrdinalIgnoreCase))
                {
                    string winlogonPath = @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon";
                    _registry.SetString(RegistryHive.LocalMachine, RegistryView.Registry64, winlogonPath, "Shell", "explorer.exe");
                    _registry.SetString(RegistryHive.LocalMachine, RegistryView.Registry64, winlogonPath, "Userinit", @"C:\Windows\system32\userinit.exe,");

                    _logger?.LogInformation("Reset Winlogon Shell and Userinit to Windows defaults.");
                    return PersistenceRemediationResult.Ok(entry.Id, "RemediateWinlogon", "Reset Winlogon Shell to 'explorer.exe' and Userinit to default.");
                }

                // 6. File / Staged Payload Remediation
                if (entry.TargetType == "File" || entry.Category.Contains("Binary", StringComparison.OrdinalIgnoreCase) || entry.Category.Contains("Script", StringComparison.OrdinalIgnoreCase))
                {
                    string filePath = entry.AdditionalData ?? entry.Location;
                    if (_fileSystem.FileExists(filePath))
                    {
                        _fileSystem.DeleteFile(filePath);
                        _logger?.LogInformation("Deleted malicious staged file: {Path}", filePath);
                        return PersistenceRemediationResult.Ok(entry.Id, "RemediateFile", $"Successfully deleted staged payload file: {filePath}");
                    }
                    return PersistenceRemediationResult.Fail(entry.Id, "RemediateFile", $"File does not exist or has already been removed: {filePath}");
                }

                return PersistenceRemediationResult.Fail(entry.Id, "Remediate", $"Unknown persistence remediation target: {entry.Category}");
            }
            catch (UnauthorizedAccessException uex)
            {
                _logger?.LogWarning(uex, "Elevation required to remediate: {Id}", entry.Id);
                return PersistenceRemediationResult.Fail(entry.Id, "Remediate", "Administrative elevation required: " + uex.Message, requiresElevation: true);
            }
            catch (SecurityException sex)
            {
                _logger?.LogWarning(sex, "Elevation required to remediate: {Id}", entry.Id);
                return PersistenceRemediationResult.Fail(entry.Id, "Remediate", "Administrative elevation required: " + sex.Message, requiresElevation: true);
            }
            catch (Exception ex)
            {
                _logger?.LogError(ex, "Remediation failed for: {Id}", entry.Id);
                return PersistenceRemediationResult.Fail(entry.Id, "Remediate", ex.Message);
            }
        }

