    }

    /// <summary>
    /// Comprehensive report generated by the persistence scanner engine.
    /// </summary>
    public sealed class PersistenceScanReport
    {
        public DateTimeOffset ScannedAt { get; init; } = DateTimeOffset.UtcNow;
        public List<PersistenceThreatItem> Threats { get; init; } = new();
        public int TotalItemsScanned { get; set; }
        public int ThreatCount => Threats.Count;
        public int CriticalCount => Threats.Count(t => t.Severity == ThreatSeverity.Critical);
